#!/usr/bin/env python3
"""Cuts single keystrokes out of a keyboard recording into src/key-hits.ts.

    python3 packages/agent-recorder/scripts/gen-key-hits.py <typing.mp3>

Each hit is 24 kHz mono 16-bit, a few ms before its attack to the start of
the next key, faded out and normalised, stored base64.
"""
import base64
import struct
import subprocess
import sys
from pathlib import Path

RATE = 24000
LEAD_MS = 3
HIT_MS = 90
FADE_MS = 25
MIN_GAP_MS = 110
MAX_HITS = 12
OUT = Path(__file__).resolve().parent.parent / "src" / "key-hits.ts"


def decode(path: str) -> list[int]:
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", str(RATE), "-f", "s16le", "-"],
        check=True,
        capture_output=True,
    ).stdout
    return list(struct.unpack(f"<{len(raw) // 2}h", raw))


def onsets(samples: list[int]) -> list[int]:
    win = RATE * 2 // 1000
    env = [max(abs(x) for x in samples[i : i + win]) for i in range(0, len(samples) - win, win)]
    peak = max(env)
    found, quiet, armed = [], 0, True
    for i, e in enumerate(env):
        if e < peak * 0.08:
            quiet += 1
            armed = True
            continue
        if e > peak * 0.25 and armed and quiet >= 6:
            found.append(i * win)
            armed = False
        quiet = 0
    return found


def cut(samples: list[int], start: int) -> list[int]:
    begin = max(0, start - RATE * LEAD_MS // 1000)
    hit = samples[begin : begin + RATE * HIT_MS // 1000]
    fade = RATE * FADE_MS // 1000
    for i in range(fade):
        hit[-1 - i] = int(hit[-1 - i] * i / fade)
    scale = 0.9 * 32767 / max(1, max(abs(x) for x in hit))
    return [int(x * scale) for x in hit]


def main() -> None:
    samples = decode(sys.argv[1])
    starts = onsets(samples)
    gap = RATE * MIN_GAP_MS // 1000
    clean = [
        s
        for i, s in enumerate(starts)
        if (i == 0 or s - starts[i - 1] >= gap)
        and (i == len(starts) - 1 or starts[i + 1] - s >= gap)
    ]
    step = max(1, len(clean) // MAX_HITS)
    hits = [cut(samples, s) for s in clean[::step][:MAX_HITS]]
    lines = ",\n".join(
        f'  "{base64.b64encode(struct.pack(f"<{len(h)}h", *h)).decode()}"' for h in hits
    )
    OUT.write_text(
        "// Generated by scripts/gen-key-hits.py from a keyboard recording.\n"
        f"export const KEY_HIT_RATE = {RATE};\n"
        f"export const KEY_HITS = [\n{lines},\n];\n"
    )
    print(f"{len(hits)} hits of {len(clean)} clean keystrokes -> {OUT}")


main()
